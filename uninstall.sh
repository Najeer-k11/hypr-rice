#!/usr/bin/env bash
# hypr-rice uninstaller. Removes what install.sh added; asks before each part.
# Packages are left installed (other things may use them): see PACKAGES.md to remove them by hand.
#   ./uninstall.sh            interactive
#   ./uninstall.sh --dry-run  print what would be removed
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DRY=0; [[ ${1:-} == --dry-run ]] && DRY=1
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
BIN_HOME="$HOME/.local/bin"

run() { printf '  $ %s\n' "$(printf '%q ' "$@")"; (( DRY )) || "$@"; }
ask() { (( DRY )) && { echo "$1 [y/N] (dry run: yes)"; return 0; }; local r; read -rp "$1 [y/N] " r </dev/tty || r=n; [[ $r =~ ^[Yy] ]]; }

if ask "Remove the scripts from $BIN_HOME (wall, lyra, rice-*)?"; then
    for f in "$REPO"/bin/*; do [[ -e "$BIN_HOME/$(basename "$f")" ]] && run rm -f "$BIN_HOME/$(basename "$f")"; done
fi

if ask "Remove the apps (rice-settings, slap-files)?"; then
    run "$REPO/apps/rice-settings/install.sh" --uninstall
    run "$REPO/apps/slap-files/install.sh" --uninstall
fi

if [[ -d /usr/share/sddm/themes/rice ]] && ask "Remove the SDDM login theme and its two config files (sudo)?"; then
    run sudo rm -rf /usr/share/sddm/themes/rice
    run sudo rm -f /etc/sddm.conf.d/10-rice.conf /etc/sddm.conf.d/20-rice-greeter.conf /etc/sddm.conf.d/30-wayland-greeter.conf
fi

if ask "Remove the config files this repo installed (and the palette files matugen generated)?"; then
    while IFS= read -r f; do [[ -e "$CONFIG_HOME/$f" ]] && run rm -f "$CONFIG_HOME/$f"; done \
        < <(cd "$REPO/config" && find . -type f | sed 's|^\./||' | sort)
    # generated by matugen (output_path lines in config/matugen/config.toml)
    while IFS= read -r f; do f="${f/#\~/$HOME}"; [[ -e $f ]] && run rm -f "$f"; done \
        < <(sed -n 's/^output_path *= *"\(.*\)"/\1/p' "$REPO/config/matugen/config.toml")
    echo "Left in place (yours): $CONFIG_HOME/hypr/local.lua, $CONFIG_HOME/hypr/settings.lua, $CONFIG_HOME/rice/, ~/.zshrc, ~/Pictures/Wallpapers"
fi

shopt -s nullglob
backups=("$CONFIG_HOME"/hypr-rice-backup-*)
if (( ${#backups[@]} )); then
    echo
    echo "Backups of the files install.sh replaced (oldest first; the oldest holds your original setup):"
    printf '  %s\n' "${backups[@]}"
    echo "Each mirrors your home folder. To restore one:  cp -a <backup>/. ~/"
fi
